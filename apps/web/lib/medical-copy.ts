export function measurementExplanation(locale: Locale, m: Measurement) {
  if (locale === "en") return m.explanation;
  const c = copy[locale];
  const key = m.comparison as
    | "above_reported_range"
    | "below_reported_range"
    | "within_reported_range"
    | "no_reference";
  return (
    c[key] +
    (m.name === "Heart rate" && m.comparison === "no_reference" && m.value > 100
      ? " " + c.heart
      : "")
  );
}
export function analysisSummary(locale: Locale, a: Analysis) {
  if (locale === "en") return a.summary;
  const c = copy[locale];
  return a.status === "unavailable"
    ? c.unavailable
    : a.measurements.length
      ? `${a.measurements.length} ${c.found}`
      : c.empty;
}
export function analysisLimitations(locale: Locale, a: Analysis) {
  if (locale === "en") return a.limitations;
  return copy[locale].limitations.slice(0, a.status === "unavailable" ? 4 : 3);
}
