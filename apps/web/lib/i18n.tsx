export type Locale = "en" | "hi" | "bn";
export type Key = keyof typeof en;
const dictionaries = { en, hi, bn };
const LocaleContext = createContext<{
  locale: Locale;
  setLocale: (value: Locale) => void;
  t: (key: Key) => string;
}>({
  locale: "en",
  setLocale: () => {},
  t: (key) => en[key],
});
function subscribe(callback: () => void) {
  window.addEventListener("storage", callback);
  window.addEventListener("medicare-language", callback);
  return () => {
    window.removeEventListener("storage", callback);
    window.removeEventListener("medicare-language", callback);
  };
}
function snapshot(): Locale {
  const value = localStorage.getItem("medicare-language");
  return value === "hi" || value === "bn" ? value : "en";
}
export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const locale = useSyncExternalStore(
    subscribe,
    snapshot,
    () => "en" as Locale,
  );
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  function setLocale(value: Locale) {
    localStorage.setItem("medicare-language", value);
    window.dispatchEvent(new Event("medicare-language"));
  }
  return (
    <LocaleContext.Provider
      value={{ locale, setLocale, t: (key) => dictionaries[locale][key] }}
    >
      {children}
    </LocaleContext.Provider>
  );
}
export function useLocale() {
  return useContext(LocaleContext);
}
